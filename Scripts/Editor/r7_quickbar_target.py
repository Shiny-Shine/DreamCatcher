"""Load/prepare or read-only verify the exact approved migrated QuickBar bundle.

Two already-ported native message types may be mapped with process-only UE config
overrides during prepare. Only new copied Blueprints are saved; a fresh verify
without those overrides must pass. No persistent Config or active UI edits.
"""
import importlib.util
import json
from pathlib import Path
import re
import sys
sys.dont_write_bytecode = True
import unreal as ue

PROJECT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location("quickbar_recipe", PROJECT / "Scripts/Editor/r7_quickbar_setup.py")
recipe = importlib.util.module_from_spec(spec)
spec.loader.exec_module(recipe)
REPORT, ROOT = recipe.REPORT, recipe.ROOT
require, digest, snapshot, clean = recipe.require, recipe.digest, recipe.snapshot, recipe.helper.clean
RELOAD = "/Game/LyraMigration/BaseInput/Actions/IA_Weapon_Reload"
STRUCTS = {"/Script/LyraGame.LyraQuickBarSlotsChangedMessage": "/Script/DreamCatcher.DCLyraQuickBarSlotsChangedMessage",
           "/Script/LyraGame.LyraQuickBarActiveIndexChangedMessage": "/Script/DreamCatcher.DCLyraQuickBarActiveIndexChangedMessage"}


def normalize(value, mapping):
    text = json.dumps(value, sort_keys=True)
    replacements = dict(mapping, **STRUCTS)
    # Read only explicit Redirect rows, never print the rest of DefaultEngine.ini.
    config = (PROJECT / "Config/DefaultEngine.ini").read_text(encoding="utf-8-sig")
    for old, new in re.findall(r'(?:Class|Struct|Function|Property)Redirects=\(OldName="([^"]+)",NewName="([^"]+)"\)', config):
        replacements[old] = new
    replacements["/Game/Input/Actions/IA_Weapon_Reload"] = RELOAD
    for old, new in sorted(replacements.items(), key=lambda p: -len(p[0])):
        text = text.replace(old, new)
    # Class-display spelling is generated by K2 when native types are redirected.
    for old, new in (("Lyra Quick Bar Component", "DCLyra Quick Bar Component"),
                     ("Lyra Inventory Item Instance", "DCInventory Item Instance"),
                     ("Lyra Inventory Item Fragment", "DCInventory Item Fragment"),
                     ("Inventory Fragment Quick Bar Icon", "DCInventory Fragment Quick Bar Icon"),
                     ("Lyra Tagged Widget", "DCLyra Tagged Widget"),
                     ("Lyra Player State", "DCPlayer State"),
                     ("Lyra Quick Bar Slots Changed Message", "DCLyra Quick Bar Slots Changed Message"),
                     ("Lyra Quick Bar Active Index Changed Message", "DCLyra Quick Bar Active Index Changed Message")):
        text = text.replace(old, new)
    return json.loads(text)


def main():
    command = ue.SystemLibrary.get_command_line()
    mode = re.search(r"-DCR7QuickTarget=(prepare|references|hard-references|styles|restore-data|verify)(?:\s|$)", command)
    run = re.search(r"-DCR7QuickRun=([A-Za-z0-9_]{1,40})(?:\s|$)", command)
    require(mode and run and "-run=pythonscript" in command.lower(), "Explicit target commandlet required")
    mode, run = mode.group(1), run.group(1)
    require(Path(ue.Paths.convert_relative_path_to_full(ue.Paths.project_dir())).resolve() == PROJECT.resolve(), "Wrong target project")
    guard = ue.DCRifleMigrationLibrary.validate_diagnostic_context()
    require(bool(guard) and (not isinstance(guard, tuple) or guard[0]), "Context refused")
    recipe.helper.LOG = PROJECT / "Saved/Logs" / ("R7Quick-" + run + ".log")
    receipt = REPORT / (run + ".json")
    require(recipe.helper.LOG.is_file() and not receipt.exists(), "Fresh log and receipt required")
    if mode == "verify":
        require("StructRedirects=" not in command, "Verification must not depend on process-only redirects")
    source = json.loads((REPORT / "prepare_A.json").read_text(encoding="utf-8"))
    mapping = source["mapping"]
    require(len(mapping) == 66 and all(d.startswith(ROOT + "/") for d in mapping.values()), "Wrong scoped manifest")
    # The user's approved intervening C++ build may update DLL/Config. Protect the
    # current invocation's target state; original Lyra files remain receipt-locked.
    protected = {p: digest(Path(p)) for p in source["protected"]}
    recipe.unchanged({p: h for p, h in source["protected"].items()
                      if Path(p).is_relative_to(recipe.SOURCE)})
    if mode == "verify":
        protected.update({str(p): digest(p) for d in mapping.values() for p in recipe.files(PROJECT, d)})
    recipe.unchanged(protected)
    editor = ue.get_editor_subsystem(ue.EditorAssetSubsystem)
    registry = ue.AssetRegistryHelpers.get_asset_registry()
    registry.search_all_assets(True)
    class_redirects = dict(re.findall(r'ClassRedirects=\(OldName="([^"]+)",NewName="([^"]+)"\)',
                          (PROJECT / "Config/DefaultEngine.ini").read_text(encoding="utf-8-sig")))
    missing_parents = sorted({row["parent"] for row in source["source_snapshots"].values()
                             if ue.find_object(None, class_redirects.get(row["parent"], row["parent"])) is None})
    require(not missing_parents, "Native parents must be ported/mapped before loading WidgetBlueprints: " + repr(missing_parents))
    if mode == "prepare":
        require(all(digest(recipe.files(PROJECT, d)[0]) == digest(recipe.files(recipe.SOURCE, d)[0])
                    for d in mapping.values()), "Target copies changed since migration; review before saving")
    all_assets = {p: ue.load_asset(d) for p, d in mapping.items()}
    require(all(all_assets.values()), "Migrated dependency did not load")
    clean()
    blueprints = {p: all_assets[p] for p in source["source_snapshots"]}
    require(len(blueprints) == 5, "Unexpected Blueprint save set")
    for bp in blueprints.values():
        ue.BlueprintEditorLibrary.compile_blueprint(bp)
    require(ue.load_asset(RELOAD), "Existing gameplay Reload action missing")
    if mode == "prepare":
        recipe.remap_reload_literal(blueprints[recipe.WIDGETS[2]],
            mapping["/Game/Input/Actions/IA_Weapon_Reload"] + ".IA_Weapon_Reload", RELOAD + ".IA_Weapon_Reload")
    ue.collect_garbage()
    differences, snapshots = {}, {}
    for p, bp in blueprints.items():
        snapshots[p] = snapshot(bp)
        expected = normalize(source["source_snapshots"][p], mapping)
        if snapshots[p] != expected:
            differences[p] = dict(before=expected, after=snapshots[p])
    if differences:
        (REPORT / (run + "_comparison.json")).write_text(json.dumps(differences, ensure_ascii=False, indent=2), encoding="utf-8")
    require(not differences, "Target graph/tree differs beyond approved type/path mapping: " + repr(list(differences)))
    clean()
    reference_saves = []
    if mode in ("restore-data", "verify") and (REPORT / "source_font_input.json").is_file():
        original_data = json.loads((REPORT / "source_font_input.json").read_text(encoding="utf-8"))
        material_data = json.loads((REPORT / "original_reference_values.json").read_text(encoding="utf-8"))
        def mapped(text):
            if text is not None:
                for old in sorted(mapping, key=len, reverse=True):
                    text = text.replace(old, mapping[old])
            return text
        changed_assets = set()
        for p, font_text in original_data["fonts"].items():
            if p not in mapping: continue
            font = all_assets[p]
            expected = mapped(font_text)
            value = font.get_editor_property("CompositeFont")
            if value.export_text() != expected:
                require(mode == "restore-data", "Composite font differs from original: " + p)
                require(value.import_text(expected), "Original composite font import failed")
                font.set_editor_property("CompositeFont", value)
                changed_assets.add(p)
            require(font.get_editor_property("CompositeFont").export_text() == expected, "Composite font restoration mismatch")
        # Restore missing material object references using original data, not only
        # the target registry (which cannot report a reference already lost to None).
        for p, row in material_data.items():
            obj = all_assets[p]
            if "expressions" not in row: continue
            is_function = isinstance(obj, ue.MaterialFunction)
            expressions = list(ue.MaterialEditingLibrary.get_material_function_expressions(obj) if is_function
                               else ue.MaterialEditingLibrary.get_material_expressions(obj))
            by_name = {e.get_name(): e for e in expressions}
            for item in row["expressions"]:
                expression = by_name[item["name"]]
                for field, original_path in item["fields"].items():
                    expected = mapped(original_path)
                    value = expression.get_editor_property(field)
                    actual = value.get_path_name() if value else None
                    if actual != expected:
                        require(mode == "restore-data", "Material field differs from original: " + p + ":" + item["name"] + "." + field)
                        replacement = ue.load_object(None, expected) if expected else None
                        require(not expected or replacement, "Original referenced asset missing")
                        expression.set_editor_property(field, replacement)
                        changed_assets.add(p)
                if "connections" in item:
                    require(list(ue.MaterialEditingLibrary.get_material_expression_input_names(expression)) == item["input_names"], "Original function input signature mismatch")
                    if mode == "restore-data":
                        for upstream, output_name, input_name in item["connections"]:
                            require(ue.MaterialEditingLibrary.connect_material_expressions(by_name[upstream], output_name, expression, input_name), "Original function connection restore failed")
                            changed_assets.add(p)
                    getter = ue.MaterialEditingLibrary.get_inputs_for_material_function_expression if is_function else ue.MaterialEditingLibrary.get_inputs_for_material_expression
                    expected_inputs = {input_name: upstream for upstream, _, input_name in item["connections"]}
                    require([v.get_name() if v else None for v in getter(obj, expression)] == [expected_inputs.get(n) for n in item["input_names"]], "Original function wiring mismatch")
        # Assign parents base-first so an instance never compiles against an
        # intentionally disconnected intermediate instance during restoration.
        visited = set()
        def restore_instance(p):
            if p in visited: return
            row = material_data[p]
            parent_package = row["parent"].split(".")[0]
            if parent_package in material_data and "parent" in material_data[parent_package]:
                restore_instance(parent_package)
            visited.add(p)
            obj = all_assets[p]
            expected_parent = mapped(row["parent"])
            parent = obj.get_editor_property("Parent")
            if not parent or parent.get_path_name() != expected_parent:
                require(mode == "restore-data", "Material instance parent differs: " + p)
                obj.set_editor_property("Parent", ue.load_object(None, expected_parent))
                changed_assets.add(p)
            for field, texts in row["parameters"].items():
                expected = [mapped(t) for t in texts]
                if [v.export_text() for v in obj.get_editor_property(field)] != expected:
                    require(mode == "restore-data", "Material parameters differ from original: " + p + "." + field)
                    struct_class = {"ScalarParameterValues": ue.ScalarParameterValue, "VectorParameterValues": ue.VectorParameterValue,
                                    "TextureParameterValues": ue.TextureParameterValue}[field]
                    values = []
                    for text in expected:
                        value = struct_class()
                        require(value.import_text(text), "Original material parameter import failed")
                        values.append(value)
                    obj.set_editor_property(field, values)
                    changed_assets.add(p)
                require([v.export_text() for v in obj.get_editor_property(field)] == expected, "Material parameter restoration mismatch")
        for p, row in material_data.items():
            if "parent" in row: restore_instance(p)
        quick = blueprints[recipe.WIDGETS[0]]
        action_widgets = [w for w in ue.ObjectIterator(ue.Widget) if w.get_path_name().startswith(quick.get_path_name() + ":WidgetTree.")
                          and w.get_name() == "InputActionWidget"]
        require(len(action_widgets) == 1 and len(original_data["inputs"]) == 1, "Unexpected input hint widget")
        expected_rows = [mapped(t) for t in original_data["inputs"][0]["rows"]]
        widget = action_widgets[0]
        if [r.export_text() for r in widget.get_editor_property("InputActions")] != expected_rows:
            require(mode == "restore-data", "Input hint row differs from original")
            rows = []
            for text in expected_rows:
                row = ue.DataTableRowHandle()
                require(row.import_text(text), "Input hint import failed")
                rows.append(row)
            widget.set_editor_property("InputActions", rows)
            changed_assets.add(recipe.WIDGETS[0])
        if mode == "restore-data":
            for p in changed_assets:
                obj = all_assets[p]
                if isinstance(obj, ue.MaterialFunction): ue.MaterialEditingLibrary.update_material_function(obj)
                elif isinstance(obj, ue.Material): ue.MaterialEditingLibrary.recompile_material(obj)
                elif isinstance(obj, ue.MaterialInstanceConstant): ue.MaterialEditingLibrary.update_material_instance(obj)
                elif isinstance(obj, ue.Blueprint): ue.BlueprintEditorLibrary.compile_blueprint(obj)
            clean()
            for p in changed_assets:
                require(editor.save_loaded_asset(all_assets[p], False), "Restored dependency save failed")
                reference_saves.append(mapping[p])
        (REPORT / (run + "_restored_data.json")).write_text(json.dumps(dict(fonts=2, materials=len(material_data), input_hints=1,
                   changed=sorted(changed_assets)), indent=2), encoding="utf-8")
    if mode in ("styles", "verify") and (REPORT / "source_brushes.json").is_file():
        original_styles = [r for r in json.loads((REPORT / "source_brushes.json").read_text(encoding="utf-8"))
                           if r["asset"] in recipe.WIDGETS]
        require(len(original_styles) == 25, "Expected the bounded original style/slot-action snapshot")
        changes = []
        # Compile leaves first, then the parent containing their designer instances.
        for original in (recipe.WIDGETS[1], recipe.WIDGETS[2], recipe.WIDGETS[0]):
            bp = blueprints[original]
            template_widgets = {w.get_name(): w for w in ue.ObjectIterator(ue.Widget)
                                if w.get_path_name().startswith(bp.get_path_name() + ":WidgetTree.")}
            for row in (r for r in original_styles if r["asset"] == original):
                expected = row["value"]
                if expected is not None:
                    for old in sorted(mapping, key=len, reverse=True):
                        expected = expected.replace(old, mapping[old])
                widget = template_widgets[row["widget"]]
                value = widget.get_editor_property(row["field"])
                actual = (value.get_path_name() if value else None) if row["kind"] == "object" else value.export_text()
                if actual != expected:
                    require(mode == "styles", "Saved style does not match original: " + repr(row))
                    if row["kind"] == "object":
                        require(actual is None and expected, "Refuse unrelated slot-action edit")
                        value = ue.load_object(None, expected)
                        require(value, "Expected copied slot action missing")
                    else:
                        require(row["kind"] in ("SlateBrush", "SlateFontInfo", "ButtonStyle"), "Unexpected style struct")
                        # Observed loss is confined to resource fields; do not mask any
                        # differences in size, margins, colors, outline or other settings.
                        empty_resources = re.sub(r'(ResourceObject|FontObject)="[^"]*"', r'\1=None', expected)
                        require(actual == empty_resources, "Style differs beyond missing resource references")
                        value = getattr(ue, row["kind"])()
                        require(value.import_text(expected), "Original style import failed")
                    widget.set_editor_property(row["field"], value)
                    changes.append(dict(asset=mapping[original], widget=row["widget"], field=row["field"]))
                current = widget.get_editor_property(row["field"])
                current_text = (current.get_path_name() if current else None) if row["kind"] == "object" else current.export_text()
                require(current_text == expected, "Style restoration mismatch")
            if mode == "styles":
                ue.BlueprintEditorLibrary.compile_blueprint(bp)
                clean()
                require(editor.save_loaded_asset(bp, False), "Restored copied widget save failed")
                reference_saves.append(mapping[original])
        (REPORT / (run + "_style_changes.json")).write_text(json.dumps(dict(checked=25, changes=changes), indent=2), encoding="utf-8")
    if mode == "hard-references":
        names = ("CA_UI_HUD", "MF_UI_RoundedCornerBorder", "M_UI_Base_HealthBar", "M_UI_Base_SimpleIcon", "M_UI_Base_WeaponCard")
        owners = {"/Game/UI/Hud/Art/" + name: all_assets["/Game/UI/Hud/Art/" + name] for name in names}
        replacements = []
        def new_reference(obj):
            if obj is None:
                return None
            p = obj.get_path_name().split(".")[0]
            return all_assets[p] if p in mapping else obj
        for p, obj in owners.items():
            if p.endswith("/CA_UI_HUD"):
                before_curves = list(obj.get_editor_property("GradientCurves"))
                after_curves = [new_reference(curve) for curve in before_curves]
                require(len(before_curves) == 12 and all(after_curves), "Unexpected curve atlas")
                require(all(old.get_path_name().split(".")[0] in mapping
                            or old.get_path_name().split(".")[0] in mapping.values() for old in before_curves), "Unexpected atlas source curves")
                obj.set_editor_property("GradientCurves", after_curves)
                require(list(obj.get_editor_property("GradientCurves")) == after_curves, "Atlas reference update failed")
                replacements.append(dict(asset=p, field="GradientCurves", count=len(after_curves)))
            else:
                is_function = p.rsplit("/", 1)[1].startswith("MF_")
                expressions = list(ue.MaterialEditingLibrary.get_material_function_expressions(obj) if is_function
                                   else ue.MaterialEditingLibrary.get_material_expressions(obj))
                def topology():
                    inputs = ue.MaterialEditingLibrary.get_inputs_for_material_function_expression if is_function else ue.MaterialEditingLibrary.get_inputs_for_material_expression
                    return [(e.get_name(), e.get_class().get_path_name(),
                             [x.get_name() if x else None for x in inputs(obj, e)]) for e in expressions]
                graph_before = topology()
                for expression in expressions:
                    fields = []
                    if isinstance(expression, ue.MaterialExpressionMaterialFunctionCall):
                        fields.append("MaterialFunction")
                    if isinstance(expression, ue.MaterialExpressionCurveAtlasRowParameter):
                        fields.extend(("Curve", "Atlas"))
                    if isinstance(expression, ue.MaterialExpressionTextureBase):
                        fields.append("Texture")
                    for field in fields:
                        old = expression.get_editor_property(field)
                        new = new_reference(old)
                        if old != new:
                            saved_connections = []
                            if field == "MaterialFunction":
                                input_names = list(ue.MaterialEditingLibrary.get_material_expression_input_names(expression))
                                get_inputs = ue.MaterialEditingLibrary.get_inputs_for_material_function_expression if is_function else ue.MaterialEditingLibrary.get_inputs_for_material_expression
                                input_nodes = list(get_inputs(obj, expression))
                                require(len(input_names) == len(input_nodes), "Function input signature unavailable")
                                require(len([n for n in input_nodes if n]) == len(set(n.get_name() for n in input_nodes if n)), "Ambiguous repeated function input source")
                                for input_name, input_node in zip(input_names, input_nodes):
                                    if input_node:
                                        output = ue.MaterialEditingLibrary.get_input_node_output_name_for_material_expression(expression, input_node)
                                        if isinstance(output, tuple):
                                            require(any(v is True for v in output), "Function input output-name lookup failed")
                                            output = next(v for v in output if isinstance(v, str))
                                        require(isinstance(output, str), "Function input output-name unavailable")
                                        saved_connections.append((input_node, output, input_name))
                            expression.set_editor_property(field, new)
                            require(expression.get_editor_property(field) == new, "Material reference update failed")
                            if field == "MaterialFunction":
                                require(list(ue.MaterialEditingLibrary.get_material_expression_input_names(expression)) == input_names,
                                        "Copied function input signature changed")
                                # FunctionInput GUIDs differ between asset copies. Restore
                                # the exact pre-swap named links through the engine API.
                                for upstream, output_name, input_name in saved_connections:
                                    require(ue.MaterialEditingLibrary.connect_material_expressions(upstream, output_name, expression, input_name),
                                            "Function connection restoration failed")
                            replacements.append(dict(asset=p, node=expression.get_name(), field=field,
                                                     old=old.get_path_name(), new=new.get_path_name()))
                graph_after = topology()
                if graph_after != graph_before:
                    (REPORT / (run + "_material_topology.json")).write_text(json.dumps(dict(
                        asset=p, before=graph_before, after=graph_after), indent=2), encoding="utf-8")
                require(graph_after == graph_before, "Material node/input topology changed: " + p)
            clean()
            require(editor.save_loaded_asset(obj, False), "New art reference save failed")
            reference_saves.append(mapping[p])
        (REPORT / (run + "_hard_reference_changes.json")).write_text(json.dumps(replacements, indent=2), encoding="utf-8")
    if mode == "references":
        options = ue.AssetRegistryDependencyOptions()
        pending = {p: [str(d) for d in registry.get_dependencies(dest, options)
                       if str(d).startswith(("/Game/", "/ShooterCore/"))
                       and str(d) not in mapping.values() and str(d) != RELOAD]
                   for p, dest in mapping.items()}
        pending = {p: refs for p, refs in pending.items() if refs}
        require(pending and set(pending).issubset(set(mapping) - set(blueprints)),
                "Unexpected reference repair scope: " + repr(pending))
        require(all(digest(recipe.files(PROJECT, mapping[p])[0]) == digest(recipe.files(recipe.SOURCE, mapping[p])[0])
                    for p in pending), "New dependency copies changed outside this recipe")
        redirects = ue.Map(ue.SoftObjectPath, ue.SoftObjectPath)
        for refs in pending.values():
            for old in refs:
                require(old in mapping, "Reference outside approved manifest")
                redirects[ue.SoftObjectPath(old + "." + old.rsplit("/", 1)[1])] = ue.SoftObjectPath(
                    mapping[old] + "." + old.rsplit("/", 1)[1])
        font_names = [p for p in pending if all_assets[p].get_class().get_path_name() == "/Script/Engine.Font"]
        font_before = {p: all_assets[p].get_editor_property("CompositeFont").export_text() for p in font_names}
        # Only packages in the approved new bundle are serialized. No global asset
        # consolidation, source asset replacement or persistent Redirect changes.
        ue.AssetToolsHelpers.get_asset_tools().rename_referencing_soft_object_paths(
            [all_assets[p].get_outer() for p in pending], redirects)
        for p in font_names:
            expected = font_before[p]
            for old in sorted(mapping, key=len, reverse=True):
                expected = expected.replace(old, mapping[old])
            require(all_assets[p].get_editor_property("CompositeFont").export_text() == expected,
                    "Composite font changed beyond object-path mapping")
        clean()
        for p in pending:
            require(editor.save_loaded_asset(all_assets[p], False), "Copied font save failed")
            reference_saves.append(mapping[p])
    if mode == "prepare":
        for bp in blueprints.values():
            require(editor.save_loaded_asset(bp, False), "New target Blueprint save failed")
    options = ue.AssetRegistryDependencyOptions()
    if reference_saves:
        registry.scan_files_synchronous([str(recipe.files(PROJECT, p)[0]) for p in reference_saves], True)
    dependencies = {d: sorted(str(p) for p in registry.get_dependencies(d, options)) for d in mapping.values()}
    (REPORT / (run + "_dependencies.json")).write_text(json.dumps(dependencies, indent=2), encoding="utf-8")
    for d, refs in dependencies.items():
        require(all(p in mapping.values() or p == RELOAD or p.startswith(("/Engine/", "/Script/")) for p in refs),
                "Unexpected content reference: " + d + " -> " + repr(refs))
    clean()
    recipe.unchanged(protected)
    receipt.write_text(json.dumps(dict(mode=mode, blueprints=snapshots, dependencies=dependencies,
                      protected=protected, reference_saves=reference_saves,
                      asset_saves=5 if mode == "prepare" else len(reference_saves)), ensure_ascii=False, indent=2), encoding="utf-8")
    print("DC_R7_QUICK_TARGET " + json.dumps(dict(event="complete", mode=mode, report=str(receipt), protected_unchanged=True)))


if __name__ == "__main__":
    main()
